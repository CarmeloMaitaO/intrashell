#[
  This section defines the cross-boundary data gateway for `dispatch`
  operations. It provides the host-side allocation hooks and a module-side
  template to  handle the serialization, memory allocation requests, and
  raw byte-copying  required to pass data safely between the main binary and
  external modules.
]#

type
  HostsAllocator* = proc(buffer: ptr Buffer, len: int, cap: int) {.cdecl.}
  ##[
    Signature of the procedure used to allocate the necessary memory on the host
    for the output of a dispatch operation from the external module. Internally,
    it just calls `preAllocateBuffer` from the `buffers.nim` module in the host.
  ]##
  ImportedDispatch* = proc(input: ptr Buffer, output: ptr Buffer, hostAllocator: HostsAllocator) {.cdecl.}
  ##[
    Signature of the dispatch procedure of a external module. It is the one that
    gets imported by the Unishell, and should be generated by the
    `dispatchBoilerplate` template.
  ]##
proc hostsAllocator*(output: ptr Buffer, len: int, cap: int) {.cdecl.} =
  ##[
    Wraps the library-provided pre-allocation logic on the host to pass it to
    the external module's dispatch method.
  ]##
  preAllocateBuffer(output, len, cap)

# Forward declaration to use it within destructors later
proc moduleShutdown(module: ImportedDispatch) {.raises: [].}

template unishellQuit*() =
  ##[
    A template for freeing all global memory from external modules, based on
    [this issue](https://github.com/nim-lang/Nim/issues/21403#issuecomment-3738505350).
    Use it inside the shutdown logic of your external module.
  ]##
  NimDestroyGlobals()
  GC_FullCollect()
  deallocOsPages()

template dispatchBoilerplate*(userSuppliedProc: UserSuppliedDispatch) =
  ##[
    This template is meant to be used by the modules (`.DLL`, `.SO`, `.WASM`) in
    order to abstract the manual serialization of data, memory management and
    FFI signature.

    The passed procedure must match the `UserSuppliedDispatch` signature.

    Example:

    ```nim
    proc yourLogic(args: seq[string]): seq[string] =
      # Here you write your custom logic
      return args

    # We then call the template. It will handle everything necessary for the FFI
    dispatchBoilerplate(yourLogic)
  ]##
  proc dispatch*(inputBuffer: ptr Buffer, outputBuffer: ptr Buffer, allocator: HostsAllocator) {.exportc, dynlib, cdecl.} =
    let
      input: seq[string] = inputBuffer[].toSeq()
      output: seq[string] = userSuppliedProc(input)
      outputLen: int = output.len()
    var outputCap: int = 0
    for element in output:
      outputCap += element.len()
    allocator(outputBuffer, outputLen, outputCap)
    # Auxiliary variables for the copy of data
    var
      dataAddress: uint = 0
      elementOffset: uint = 0
    if outputLen > 0:
      dataAddress = cast[uint](outputBuffer[].data)
      for index, element in pairs(output):
        outputBuffer.sizes[index] = element.len
        if element.len > 0:
          outputBuffer.offsets[index] = elementOffset
          copyMem(cast[pointer](dataAddress + elementOffset), addr element[0], element.len)
        elementOffset += (element.len).uint

