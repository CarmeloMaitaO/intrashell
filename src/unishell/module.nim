proc castPointerToString*(p: pointer): string =
  ##[
    Used to send through the `shell` procedure a pointer to some data structure.
    Example:

    ```nim
    var someString: string = "some text"
    
    echo someModule.shell(castPointerToString(addr someString))
    ```
  ]##
  return $(cast[int](p))

proc castStringToPointer*(p: string): pointer =
  ##[
    Used to receive through the `dispatch` procedure a pointer to some data structure.
    Example:

    ```nim
    var someObjectPtr: ptr SomeObject = castStringToPointer(arg)
    ```
  ]##
  return cast[pointer](p.parseUInt)

template dispatchBoilerplate*(userSuppliedProc: UserSuppliedDispatch) =
  ##[
    This template is meant to be used by the modules (`.DLL`, `.SO`, `.WASM`) in
    order to abstract the manual serialization of data, memory management and
    FFI signature.

    The passed procedure must match the `UserSuppliedDispatch` signature.

    Example:

    ```nim
    proc yourLogic(args: seq[string]): seq[string] =
      # Here you write your custom logic
      return args

    # We then call the template. It will handle everything necessary for the FFI
    dispatchBoilerplate(yourLogic)
  ]##
  proc dispatch*(inputBuffer: Buffer, outputBuffer: var Buffer, allocator: HostAllocator) {.exportc, dynlib, cdecl, raises: [WrongParameters, CommandFailed].} =
    let
      inputView: BufferView = inputBuffer.newBufferView()
      inputSeq: seq[string] = inputView.toSeq()
      output: seq[string] = userSuppliedProc(inputSeq)
    outputBuffer.newBuffer(output, allocator)
