const dynamicModuleExtensions = [
  "dll",
  "so",
  "dylib"
]

# When this option is enabled, the DynamicModule type doesn't exists, and therefore the loadDynamicModule should return a Module, which is a type that exists
when defined(unishellDisableDynamicModules):
  proc loadDynamicModule(path: Path, identity: string, version: Version): Module =
    result = nil
else:
  import std/dynlib

  type
    DynamicModulePayloadObj* = object
      ##[
        Holds the actual pointers to the external module and it's procedure. It is
        declared as it's own object to facilitate the implementation of a custom
        destructor
      ]##
      lib*: LibHandle
        ##[
          Handle for the dynamic library.
        ]##
      importedDispatch*: ImportedDispatch
    DynamicModulePayload* = ref DynamicModulePayloadObj
    DynamicModule* = ref object of Module
      ##[
        Object that represents an external module in the form of a
        dynamic/shared library. It is not meant to be created manually by the
        user.
      ]##
      path*: Path
      ##[
        Absolute path to the dynamic library. It is used to identify the file
        that corresponds to the currently loaded module.
      ]##
      payload*: DynamicModulePayload 

  proc `=destroy`*(payload: var DynamicModulePayloadObj) =
    if payload.importedDispatch != nil:
      payload.importedDispatch.moduleShutdown()
      payload.importedDispatch = nil
    if payload.lib != nil:
      unloadLib(payload.lib)

  method dispatch*(
    module: DynamicModule,
    input: Buffer
  ): Buffer =
    var output: Buffer
    if module.payload.importedDispatch != nil:
      module.payload.importedDispatch(
        addr input,
        addr output,
        hostsAllocator
      )
      result = output
    else:
      result = createBuffer(@[])

  proc loadDynamicModule(path: Path, identity: string, version: Version): DynamicModule =
    var splittedFile = splitFile(path)
    if fileExists(path) and (splittedFile.ext in dynamicModuleExtensions):
      new(result)
      result.identity = identity
      result.version = version
      result.payload = new(DynamicModulePayload)
      result.payload.lib = loadLib($path)
      result.payload.importedDispatch = cast[ImportedDispatch](
        result.payload.lib.symAddr("dispatch")
      )
    else:
      result = nil

